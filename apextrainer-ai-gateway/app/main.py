# Internal ApexTrainer endpoint used to verify the user's existing login session.
# The browser never sends a trusted user ID directly to the AI Gateway.
# Instead, the Gateway forwards the login cookie to the ApexTrainer backend
# and asks the backend to identify the currently authenticated user.
AUTH_VERIFY_URL = os.getenv(
    "AUTH_VERIFY_URL",
    "http://apextrainer-server:3010/api/identity/user",
)

# Langflow flow endpoint used by the production ApexTrainer chat.
LANGFLOW_RUN_URL = os.getenv(
    "LANGFLOW_RUN_URL",
    (
        "http://apextrainer-langflow:7860/"
        "api/v1/run/apextrainer-chatbot?stream=false"
    ),
)

# API key used only to authenticate the AI Gateway itself to Langflow.
# This is NOT the user's MCP credential.
LANGFLOW_API_KEY = os.getenv(
    "LANGFLOW_API_KEY",
    "",
).strip()

# ID of the Langflow custom component that receives trusted user/session context.
LANGFLOW_COMPONENT_ID = os.getenv(
    "LANGFLOW_COMPONENT_ID",
    "CustomComponent-M3tu3",
)

# Maximum time the AI Gateway waits for Langflow to return a response.
LANGFLOW_TIMEOUT_SECONDS = float(
    os.getenv(
        "LANGFLOW_TIMEOUT_SECONDS",
        "120",
    )
)

# Simple per-user rate limit for the chatbot.
RATE_LIMIT_PER_MINUTE = int(
    os.getenv(
        "RATE_LIMIT_PER_MINUTE",
        "20",
    )
)


# =============================================================================
# MCP per-user authentication configuration
# =============================================================================

# Shared signing secret known only by:
#   1. ApexTrainer AI Gateway
#   2. ApexTrainer MCP server
#
# The secret itself is NEVER sent to Langflow.
# Langflow receives only a short-lived signed JWT.
MCP_GATEWAY_JWT_SECRET = os.getenv(
    "MCP_GATEWAY_JWT_SECRET",
    "",
).strip()

# Short lifetime reduces the impact if a token is ever exposed.
# Default: 300 seconds = 5 minutes.
MCP_GATEWAY_JWT_TTL_SECONDS = int(
    os.getenv(
        "MCP_GATEWAY_JWT_TTL_SECONDS",
        "300",
    )
)

# Issuer and audience are checked by the MCP server.
# These values help prevent the token from being accepted by another service.
MCP_GATEWAY_JWT_ISSUER = "apextrainer-ai-gateway"
MCP_GATEWAY_JWT_AUDIENCE = "apextrainer-mcp"


