class ChatRequest(BaseModel):
    # Limit chat input size to reduce abuse and unexpectedly large requests.
    message: str = Field(
        min_length=1,
        max_length=2000,
    )

    # Generated by the frontend and used only to group one conversation.
    conversation_id: UUID


class ChatResponse(BaseModel):
    answer: str
    conversation_id: UUID


# =============================================================================
# In-memory per-user rate limiting
# =============================================================================

request_history: dict[str, deque[float]] = defaultdict(
    deque
)


def enforce_rate_limit(user_id: str) -> None:
    """
    Apply a simple sliding one-minute rate limit per authenticated user.

    This prevents one authenticated user from flooding the AI endpoint.
    """

    now = time.monotonic()
    window_start = now - 60

    history = request_history[user_id]

    # Remove requests that are older than the current one-minute window.
    while history and history[0] < window_start:
        history.popleft()

    if len(history) >= RATE_LIMIT_PER_MINUTE:
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail=(
                "Too many AI requests. "
                "Please wait and try again."
            ),
        )

    history.append(now)


# =============================================================================
# ApexTrainer identity handling
# =============================================================================

def find_active_user_id(data: Any) -> str | None:
    """
    Extract the active authenticated user ID from common response formats
    returned by the ApexTrainer identity endpoint.

    The function supports several possible API response shapes so that the
    Gateway remains compatible with small backend response changes.
    """

    if not isinstance(data, dict):
        return None

    active_user_id = data.get("activeUserId")

    if active_user_id:
        return str(active_user_id)

    user = data.get("user")

    if isinstance(user, dict) and user.get("id"):
        return str(user["id"])

    nested_data = data.get("data")

    if isinstance(nested_data, dict):
        active_user_id = nested_data.get(
            "activeUserId"
        )

        if active_user_id:
            return str(active_user_id)

        nested_user = nested_data.get("user")

        if (
            isinstance(nested_user, dict)
            and nested_user.get("id")
        ):
            return str(nested_user["id"])

    return None


async def get_verified_user_id(
    request: Request,
) -> str:
    """
    Verify the existing ApexTrainer browser session.

    Security principle:
    The frontend is NOT allowed to decide which user ID the AI should use.

    Instead:
        Browser cookie
            -> AI Gateway
            -> ApexTrainer backend
            -> authenticated user ID

    This prevents a user from manually changing a user ID in the chat request
    and accessing another user's fitness information.
    """

    cookie = request.headers.get(
        "cookie",
        "",
    ).strip()

    if not cookie:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
        )

    # Forward only the headers required for session verification.
    forwarded_headers = {
        "Cookie": cookie,
        "Accept": "application/json",
    }

    user_agent = request.headers.get(
        "user-agent"
    )

    if user_agent:
        forwarded_headers["User-Agent"] = user_agent

    origin = request.headers.get("origin")

    if origin:
        forwarded_headers["Origin"] = origin

    try:
        async with httpx.AsyncClient(
            timeout=httpx.Timeout(10.0),
        ) as client:
            response = await client.get(
                AUTH_VERIFY_URL,
                headers=forwarded_headers,
            )

    except httpx.RequestError as error:
        print(
            "[Auth] Backend connection error:",
            repr(error),
        )

        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "Authentication service is "
                "currently unavailable."
            ),
        ) from error

    # Invalid or expired user login session.
    if response.status_code in (401, 403):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=(
                "Your login session is invalid "
                "or expired."
            ),
        )

    if not response.is_success:
        print(
            "[Auth] Unexpected status:",
            response.status_code,
            response.text[:500],
        )

        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "Authentication verification failed."
            ),
        )

    try:
        identity_data = response.json()
    except ValueError as error:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "Authentication service returned "
                "invalid data."
            ),
        ) from error

    user_id = find_active_user_id(
        identity_data
    )

    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=(
                "No authenticated active user "
                "was found."
            ),
        )

    return user_id


# =============================================================================
# Short-lived MCP user token
# =============================================================================

def create_mcp_user_token(
    user_id: str,
) -> str:
    """
    Create a short-lived JWT representing the authenticated ApexTrainer user.

    Important:
    - The browser cannot create this token.
    - Langflow cannot create this token.
    - Only the trusted AI Gateway can sign it.
    - The MCP server verifies the signature before trusting the user ID.

    JWT claims:
        sub -> authenticated ApexTrainer user ID
        iss -> token issuer
        aud -> intended MCP service
        iat -> issued-at timestamp
        exp -> expiration timestamp
    """

    if not MCP_GATEWAY_JWT_SECRET:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "MCP user authentication "
                "is not configured."
            ),
        )

    now = int(time.time())

    payload = {
        # "sub" is the trusted authenticated ApexTrainer user ID.
        "sub": user_id,

        # Identifies who created the token.
        "iss": MCP_GATEWAY_JWT_ISSUER,

        # Restricts where the token is intended to be accepted.
        "aud": MCP_GATEWAY_JWT_AUDIENCE,

        # Token creation time.
        "iat": now,

        # Token expires shortly after creation.
        "exp": (
            now
            + MCP_GATEWAY_JWT_TTL_SECONDS
        ),
    }

    return jwt.encode(
        payload,
        MCP_GATEWAY_JWT_SECRET,
        algorithm="HS256",
    )


# =============================================================================
# Langflow response parsing
# =============================================================================

def get_nested_value(
    data: Any,
    path: tuple[Any, ...],
) -> Any:
    """
    Safely retrieve a value from a deeply nested Langflow response.
    """

    current = data

    for part in path:
        if isinstance(part, int):
            if (
                not isinstance(current, list)
                or part >= len(current)
            ):
                return None

            current = current[part]

        else:
            if not isinstance(current, dict):
                return None

            current = current.get(part)

        if current is None:
            return None

    return current


def extract_langflow_answer(
    data: Any,
) -> str:
    """
    Extract the assistant text from several Langflow response formats.

    Langflow responses can differ slightly depending on flow components and
    versions, so multiple supported paths are checked.
    """

    possible_paths = [
        (
            "outputs",
            0,
            "outputs",
            0,
            "results",
            "message",
            "text",
        ),
        (
            "outputs",
            0,
            "outputs",
            0,
            "results",
            "message",
            "data",
            "text",
        ),
        (
            "outputs",
            0,
            "outputs",
            0,
            "artifacts",
            "message",
        ),
        (
            "outputs",
            0,
            "outputs",
            0,
            "outputs",
            "message",
            "message",
            "text",
        ),
        ("message",),
        ("text",),
    ]

    for path in possible_paths:
        value = get_nested_value(
            data,
            path,
        )

        if (
            isinstance(value, str)
            and value.strip()
        ):
            return value.strip()

    return ""


