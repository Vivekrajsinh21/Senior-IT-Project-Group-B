@app.post(
    "/chat",
    response_model=ChatResponse,
)
async def chat(
    body: ChatRequest,
    request: Request,
) -> ChatResponse:
    """
    Main authenticated ApexTrainer AI chat endpoint.

    Request flow:

        Browser
          -> /api/ai/chat
          -> AI Gateway verifies Better Auth session
          -> Gateway determines trusted user ID
          -> Gateway creates short-lived MCP JWT
          -> Gateway sends user context + JWT to Langflow
          -> Langflow forwards JWT to ApexTrainer MCP
          -> MCP verifies JWT and uses its "sub" as the user ID
          -> MCP tools query only that user's data
    """

    if not LANGFLOW_API_KEY:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "AI Gateway is missing its "
                "Langflow API key."
            ),
        )

    message = body.message.strip()

    if not message:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Message cannot be empty.",
        )

    # -------------------------------------------------------------------------
    # Step 1: Verify the user's real login session.
    # -------------------------------------------------------------------------

    verified_user_id = (
        await get_verified_user_id(request)
    )

    try:
        await ensure_conversation(
            verified_user_id,
            body.conversation_id,
            message,
        )
    except PermissionError as error:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Conversation access denied.",
        ) from error

    # -------------------------------------------------------------------------
    # Step 2: Apply rate limiting using the trusted authenticated user ID.
    # -------------------------------------------------------------------------

    enforce_rate_limit(
        verified_user_id
    )

    # -------------------------------------------------------------------------
    # Step 3: Build a trusted Langflow session ID.
    #
    # The session ID contains the verified user ID and frontend conversation ID.
    # This keeps conversation memory separated between users/conversations.
    # -------------------------------------------------------------------------

    langflow_session_id = (
        f"apextrainer:"
        f"{verified_user_id}:"
        f"{body.conversation_id}"
    )

    # -------------------------------------------------------------------------
    # Step 4: Create a short-lived MCP credential for THIS authenticated user.
    #
    # This replaces the security role previously played by a single static
    # production MCP API key.
    # -------------------------------------------------------------------------

    mcp_user_token = create_mcp_user_token(
        verified_user_id
    )

    # -------------------------------------------------------------------------
    # Step 5: Build the Langflow payload.
    #
    # The tweak provides user context to the custom Langflow component.
    # Important: this user ID is useful context, but MCP authorization must
    # still rely on the cryptographically signed JWT.
    # -------------------------------------------------------------------------

    langflow_payload = {
        "input_value": message,
        "input_type": "chat",
        "output_type": "chat",
        "session_id": langflow_session_id,

        "tweaks": {
            LANGFLOW_COMPONENT_ID: {
                "apextrainer_user_id": (
                    verified_user_id
                ),
                "langflow_session_id": (
                    langflow_session_id
                ),
            }
        },
    }

    try:
        async with httpx.AsyncClient(
            timeout=httpx.Timeout(
                LANGFLOW_TIMEOUT_SECONDS,
                connect=10.0,
            ),
        ) as client:

            response = await client.post(
                LANGFLOW_RUN_URL,

                headers={
                    # Langflow API request format.
                    "Content-Type": (
                        "application/json"
                    ),

                    # Authenticates this Gateway to Langflow.
                    "x-api-key": (
                        LANGFLOW_API_KEY
                    ),

                    # ---------------------------------------------------------
                    # Request-scoped Langflow global variable.
                    #
                    # Langflow makes MCP_USER_TOKEN available only while this
                    # particular flow request is executing.
                    #
                    # In the Langflow MCP server configuration, the value of
                    # the Authorization header will reference MCP_USER_TOKEN.
                    #
                    # The value already includes the "Bearer " prefix.
                    # ---------------------------------------------------------
                    "X-LANGFLOW-GLOBAL-VAR-MCP_USER_TOKEN": (
                        f"Bearer {mcp_user_token}"
                    ),
                },

                json=langflow_payload,
            )

    except httpx.TimeoutException as error:
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail=(
                "The AI service took too long "
                "to respond."
            ),
        ) from error

    except httpx.RequestError as error:
        print(
            "[Langflow] Connection error:",
            repr(error),
        )

        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "The AI service is currently "
                "unavailable."
            ),
        ) from error

    if not response.is_success:
        print(
            "[Langflow] Error:",
            response.status_code,
            response.text[:1000],
        )

        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "The AI service returned an error."
            ),
        )

    try:
        langflow_data = response.json()

    except ValueError as error:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "The AI service returned "
                "invalid data."
            ),
        ) from error

    answer = extract_langflow_answer(
        langflow_data
    )

    if not answer:
        print(
            "[Langflow] No readable answer:",
            str(langflow_data)[:1000],
        )

        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "The AI service returned "
                "no readable answer."
            ),
        )

    try:
        await append_exchange(
            verified_user_id,
            body.conversation_id,
            message,
            answer,
        )
    except PermissionError as error:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Conversation access denied.",
        ) from error

    return ChatResponse(
        answer=answer,
        conversation_id=body.conversation_id,
    )
